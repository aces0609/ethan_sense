"""The fiscal calendar is read from the facts, not from EDGAR's declared fiscalYearEnd.

L3Harris (52/53-week year ending the Friday nearest 31 December, declared "0102") came out
as FY2021, 2022, 2024, 2025 with no FY2025 revenue: the month rule labelled every December
period end a year early and the balance-sheet filter wanted January. These tests run on the
real L3Harris companyfacts (tests/fixtures/edgar/companyfacts_LHX.json, regenerated by
make_fixtures.py) and on small synthetic filers with June and September year ends, one of
them with a wrong declared year end."""

from __future__ import annotations

import json
from datetime import date, timedelta
from pathlib import Path
from typing import Any

import pytest

from primer.clients.edgar import (
    AnnualFinancials,
    EdgarClient,
    FiscalCalendar,
    build_fiscal_calendar,
    describe_fiscal_year_end,
    fiscal_year_label,
    quarter_label,
)

FIXTURES = Path(__file__).parent / "fixtures" / "edgar"
LHX_CIK = "0000202058"
AS_OF = date(2026, 10, 22)
ANNUAL_FORMS = {"10-K", "10-K/A", "10-KT"}
CORE_METRICS = (
    "revenue",
    "operating_income",
    "net_income",
    "operating_cash_flow",
    "capex",
    "cash",
    "total_assets",
    "total_debt",
)


def _lhx_facts() -> dict[str, Any]:
    return json.loads((FIXTURES / "companyfacts_LHX.json").read_text(encoding="utf-8"))


def _client(facts: dict[str, Any], monkeypatch, declared: str | None = "1231") -> EdgarClient:
    client = EdgarClient()
    monkeypatch.setattr(client, "companyfacts", lambda cik: facts)
    monkeypatch.setattr(client, "_fye_from_submissions", lambda cik: declared)
    return client


def _without_quarterly(facts: dict[str, Any]) -> dict[str, Any]:
    out: dict[str, Any] = {"facts": {}}
    for tax, concepts in facts["facts"].items():
        for concept, node in concepts.items():
            units = {
                u: [e for e in es if e["form"].startswith("10-K")]
                for u, es in node["units"].items()
            }
            out["facts"].setdefault(tax, {})[concept] = {"units": units}
    return out


# ---- L3Harris, real data ------------------------------------------------------------------


@pytest.fixture
def lhx(monkeypatch, output_dir) -> AnnualFinancials:
    # the declared year end is deliberately the wrong "1231": it must not matter
    return _client(_lhx_facts(), monkeypatch).annual_financials(LHX_CIK, as_of=AS_OF)


def test_lhx_has_four_consecutive_fiscal_years_fy2022_to_fy2025(lhx):
    assert lhx.fiscal_years == [2022, 2023, 2024, 2025]
    assert lhx.fiscal_years == list(range(lhx.fiscal_years[0], lhx.fiscal_years[-1] + 1))
    for metric in CORE_METRICS:
        for fy in lhx.fiscal_years:
            assert lhx.value(metric, fy) is not None, (metric, fy)
    assert {fy: lhx.facts["revenue"][fy].end for fy in lhx.fiscal_years} == {
        2022: date(2022, 12, 30),
        2023: date(2023, 12, 29),
        2024: date(2025, 1, 3),
        2025: date(2026, 1, 2),
    }
    assert lhx.fiscal_year_ends == {
        2022: date(2022, 12, 30),
        2023: date(2023, 12, 29),
        2024: date(2025, 1, 3),
        2025: date(2026, 1, 2),
    }


def test_lhx_fy2025_is_the_period_ending_2026_01_02(lhx):
    got = {m: lhx.value(m, 2025) for m in CORE_METRICS}
    assert got == {
        "revenue": 21_865e6,
        "operating_income": 2_110e6,
        "net_income": 1_606e6,
        "operating_cash_flow": 3_106e6,
        "capex": 424e6,
        "cash": 1_069e6,
        "total_assets": 41_195e6,
        "total_debt": 10_443e6,
    }
    for fv in (lhx.facts[m][2025] for m in ("revenue", "net_income", "cash", "total_assets")):
        assert fv.end == date(2026, 1, 2) and fv.period_label == "FY2025"
    assert lhx.facts["revenue"][2022].value == 17_062e6  # period ending 2022-12-30
    assert lhx.facts["revenue"][2023].value == 19_419e6  # period ending 2023-12-29


def test_lhx_balance_sheet_identity_holds_in_each_year(lhx):
    for fy in lhx.fiscal_years:
        assets = lhx.value("total_assets", fy)
        liabilities = lhx.value("total_liabilities", fy)
        equity = lhx.value("stockholders_equity", fy)
        assert assets and liabilities and equity, fy
        assert abs(assets - (liabilities + equity)) / assets < 0.005, (fy, assets)


def test_lhx_cover_page_shares_attach_to_the_right_year(lhx):
    assert lhx.value("shares_outstanding", 2025) == 186_776_263
    assert lhx.value("shares_outstanding", 2024) == 188_313_839
    assert lhx.value("shares_outstanding", 2023) == 190_107_856
    assert lhx.value("shares_outstanding", 2022) == 190_089_405
    # each share count is dated shortly after its own fiscal year end
    assert lhx.facts["shares_outstanding"][2025].end == date(2026, 1, 2)


def test_lhx_displays_the_observed_year_end_not_the_declared_one(lhx):
    assert lhx.fiscal_year_end == "52/53-week year ending 2026-01-02"
    assert lhx.fiscal_year_end_date == date(2026, 1, 2)
    assert lhx.fiscal_year_end_phrase == "52/53-week fiscal years, latest ending 2026-01-02"


@pytest.mark.parametrize("declared", ["0102", "1231", "0630", None])
def test_lhx_result_does_not_depend_on_the_declared_year_end(monkeypatch, output_dir, declared):
    client = _client(_lhx_facts(), monkeypatch, declared=declared)
    fin = client.annual_financials(LHX_CIK, fiscal_year_end=declared, as_of=AS_OF)
    assert fin.fiscal_years == [2022, 2023, 2024, 2025]
    assert fin.value("revenue", 2025) == 21_865e6
    assert fin.value("total_assets", 2022) == 33_524e6


def test_lhx_fy2025_revenue_is_a_year_tagged_with_a_quarter_period(lhx):
    """The FY2025 10-K gives revenue for 2025-10-04..2026-01-02 only. It is the whole year:
    it exceeds the nine-month year-to-date value, so it is taken as the fiscal year and says so."""
    fv = lhx.facts["revenue"][2025]
    assert fv.value == 21_865e6 and fv.start == date(2025, 1, 4)
    assert fv.note and "2025-10-04" in fv.note and "nine-month" in fv.note
    assert lhx.facts["revenue"][2024].note is None


def test_lhx_fy2025_revenue_is_not_guessed_without_the_nine_month_fact(monkeypatch, output_dir):
    client = _client(_without_quarterly(_lhx_facts()), monkeypatch)
    fin = client.annual_financials(LHX_CIK, as_of=AS_OF)
    assert fin.value("revenue", 2025) is None and "revenue" in fin.missing
    assert fin.value("net_income", 2025) == 1_606e6  # other metrics are unaffected


def test_lhx_quarterly_series_takes_q4_from_the_year_not_the_mistagged_fact(
    monkeypatch, output_dir
):
    client = _client(_lhx_facts(), monkeypatch)
    series = client.quarterly_series(LHX_CIK, ("revenue", "operating_income"), as_of=AS_OF)
    rev = {fv.period_label: fv for fv in series["revenue"]}
    # 2026-01-02 closes calendar Q4-2025; the filed 91-day $21.9bn "quarter" is the year
    assert rev["Q4-2025"].taxonomy == "derived"
    assert rev["Q4-2025"].value == 21_865e6 - 16_217e6
    assert rev["Q4-2025"].end == date(2026, 1, 2) and rev["Q4-2025"].fiscal_year == 2025
    assert all(fv.value < 10_000e6 for fv in series["revenue"])
    assert [rev[q].end for q in ("Q1-2025", "Q2-2025", "Q3-2025")] == [
        date(2025, 3, 28),
        date(2025, 6, 27),
        date(2025, 10, 3),
    ]
    assert rev["Q1-2026"].end == date(2026, 4, 3) and rev["Q2-2026"].end == date(2026, 7, 3)


# ---- synthetic filers ---------------------------------------------------------------------


def _filer(
    ends: dict[int, date],
    *,
    filed_after_days: int = 50,
    fy_of: dict[int, int | None] | None = None,
) -> dict[str, Any]:
    """companyfacts for a filer with one 10-K per label in `ends` (label -> period end). Each
    10-K carries the current year and two comparatives (income statement), the current and
    prior balance sheet and a cover-page share count dated 5 days before the filing. Values
    are label * 1000 so a fact's year is visible in its value."""
    durations = {
        "Revenues": 10,
        "OperatingIncomeLoss": 2,
        "NetIncomeLoss": 1,
        "NetCashProvidedByUsedInOperatingActivities": 3,
        "PaymentsToAcquirePropertyPlantAndEquipment": 1,
    }
    instants = {
        "CashAndCashEquivalentsAtCarryingValue": 2,
        "Assets": 20,
        "Liabilities": 12,
        "StockholdersEquity": 8,
        "LongTermDebtNoncurrent": 5,
        "LongTermDebtCurrent": 1,
    }
    us: dict[str, list[dict[str, Any]]] = {c: [] for c in (*durations, *instants)}
    cover: list[dict[str, Any]] = []
    labels = sorted(ends)
    for k, label in enumerate(labels):
        filed_d = ends[label] + timedelta(days=filed_after_days)
        accn = f"0000000001-{label % 100:02d}-000001"
        fy = (fy_of or {}).get(label, label)
        common = {"accn": accn, "form": "10-K", "filed": filed_d.isoformat(), "fp": "FY"}
        if fy is not None:
            common["fy"] = fy
        for back in range(3):  # current year and two comparatives
            if k - back < 0:
                continue
            lab = labels[k - back]
            end = ends[lab]
            start = ends[labels[k - back - 1]] + timedelta(days=1) if k - back > 0 else None
            if start is None:
                start = end - timedelta(days=364)
            for concept, mult in durations.items():
                us[concept].append(
                    {
                        **common,
                        "start": start.isoformat(),
                        "end": end.isoformat(),
                        "val": lab * 1000 * mult,
                    }
                )
            if back < 2:
                for concept, mult in instants.items():
                    us[concept].append({**common, "end": end.isoformat(), "val": lab * 1000 * mult})
        cover.append(
            {**common, "end": (filed_d - timedelta(days=5)).isoformat(), "val": label * 100}
        )
    return {
        "cik": 1,
        "entityName": "Synthetic",
        "facts": {
            "us-gaap": {c: {"units": {"USD": v}} for c, v in us.items()},
            "dei": {"EntityCommonStockSharesOutstanding": {"units": {"shares": cover}}},
        },
    }


JUNE = {y: date(y, 6, 30) for y in range(2021, 2026)}
# 52/53-week September year end: the last Saturday of September
SEPTEMBER = {
    2021: date(2021, 10, 2),
    2022: date(2022, 10, 1),
    2023: date(2023, 9, 30),
    2024: date(2024, 9, 28),
    2025: date(2025, 9, 27),
}


def test_june_year_end_labels_the_period_ending_2025_06_30_as_fy2025(monkeypatch, output_dir):
    # EDGAR declares "1231" for this filer; its year really ends June 30
    fin = _client(_filer(JUNE), monkeypatch).annual_financials(
        "0000000001", fiscal_year_end="1231", as_of=AS_OF
    )
    assert fin.fiscal_years == [2022, 2023, 2024, 2025]
    assert fin.facts["revenue"][2025].end == date(2025, 6, 30)
    assert fin.value("revenue", 2025) == 2025 * 1000 * 10
    assert fin.value("total_assets", 2025) == 2025 * 1000 * 20
    assert fin.value("total_assets", 2022) == 2022 * 1000 * 20  # a comparative balance sheet
    # the cover-page count (dated Aug 2025) belongs to FY2025, not to the year before
    assert fin.value("shares_outstanding", 2025) == 2025 * 100
    assert fin.value("shares_outstanding", 2024) == 2024 * 100
    assert fin.facts["shares_outstanding"][2025].end == date(2025, 6, 30)
    assert (
        fin.fiscal_year_end == "06/30" and fin.fiscal_year_end_phrase == "fiscal years ending 06/30"
    )
    assert not fin.missing.get("total_assets") and not fin.missing.get("revenue")


def test_declared_year_end_is_not_consulted_when_every_filing_has_fy(monkeypatch, output_dir):
    client = _client(_filer(JUNE), monkeypatch)

    def boom(cik):  # the fallback month must not even be looked up
        raise AssertionError("declared fiscalYearEnd was read")

    monkeypatch.setattr(client, "_fye_from_submissions", boom)
    fin = client.annual_financials("0000000001", as_of=AS_OF)
    assert fin.fiscal_years == [2022, 2023, 2024, 2025]


def test_september_52_53_week_year_end(monkeypatch, output_dir):
    fin = _client(_filer(SEPTEMBER, filed_after_days=45), monkeypatch).annual_financials(
        "0000000001", fiscal_year_end="1231", as_of=AS_OF
    )
    assert fin.fiscal_years == [2022, 2023, 2024, 2025]
    # a period ending 2022-10-01 is FY2022 and one ending 2025-09-27 is FY2025
    assert fin.facts["revenue"][2022].end == date(2022, 10, 1)
    assert fin.facts["revenue"][2025].end == date(2025, 9, 27)
    assert fin.value("total_assets", 2022) == 2022 * 1000 * 20
    assert fin.value("total_assets", 2025) == 2025 * 1000 * 20
    assert fin.value("shares_outstanding", 2025) == 2025 * 100
    assert fin.value("shares_outstanding", 2023) == 2023 * 100
    assert fin.fiscal_year_end == "52/53-week year ending 2025-09-27"


def test_september_standard_year_end_prints_mm_dd(monkeypatch, output_dir):
    sept = {y: date(y, 9, 30) for y in range(2021, 2026)}
    fin = _client(_filer(sept), monkeypatch).annual_financials("0000000001", as_of=AS_OF)
    assert fin.fiscal_years == [2022, 2023, 2024, 2025]
    assert fin.fiscal_year_end == "09/30"
    assert fin.value("shares_outstanding", 2024) == 2024 * 100


def test_filing_without_fy_falls_back_to_the_month_rule(monkeypatch, output_dir):
    facts = _filer(JUNE, fy_of={2023: None, 2025: None})
    # the 10-K for 2023 and 2025 carry no fy; the declared month (06) labels them by period end
    fin = _client(facts, monkeypatch, declared="0630").annual_financials("0000000001", as_of=AS_OF)
    assert fin.fiscal_years == [2022, 2023, 2024, 2025]
    assert fin.facts["revenue"][2025].end == date(2025, 6, 30)
    assert fin.facts["revenue"][2023].end == date(2023, 6, 30)


def test_implausible_fy_is_ignored(monkeypatch, output_dir):
    # a mis-tagged DocumentFiscalYearFocus (2030 for a period ending in 2025) is not trusted
    facts = _filer(JUNE, fy_of={2025: 2030})
    fin = _client(facts, monkeypatch, declared="0630").annual_financials("0000000001", as_of=AS_OF)
    assert fin.fiscal_years == [2022, 2023, 2024, 2025]
    assert fin.facts["revenue"][2025].end == date(2025, 6, 30)


def test_comparative_period_takes_fy_minus_years_back():
    cal = build_fiscal_calendar(_filer(SEPTEMBER), ANNUAL_FORMS, AS_OF)
    assert cal.labels[date(2025, 9, 27)] == 2025
    assert cal.labels[date(2024, 9, 28)] == 2024
    assert cal.labels[date(2022, 10, 1)] == 2022
    assert cal.labels[date(2021, 10, 2)] == 2021


def test_current_period_of_a_filing_wins_over_a_conflicting_comparative():
    # a later 10-K/A mis-tags its fy one year early (2024 for a period ending 2025-06-30), so it
    # calls the period ending 2024-06-30 "2023"; the 2024 10-K, where that period is current,
    # decides
    facts = _filer(JUNE)
    late = {
        "start": "2023-07-01",
        "end": "2024-06-30",
        "val": 1,
        "accn": "0000000009-26-000001",
        "form": "10-K/A",
        "filed": "2026-08-01",
        "fy": 2024,
        "fp": "FY",
    }
    current = dict(late, start="2024-07-01", end="2025-06-30")
    facts["facts"]["us-gaap"]["Revenues"]["units"]["USD"].extend([late, current])
    cal = build_fiscal_calendar(facts, ANNUAL_FORMS, AS_OF)
    assert cal.labels[date(2024, 6, 30)] == 2024


def test_calendar_helpers():
    cal = FiscalCalendar(labels={date(2025, 1, 3): 2024, date(2026, 1, 2): 2025})
    assert cal.instant_period(date(2025, 12, 31)) == date(2026, 1, 2)
    assert cal.instant_period(date(2025, 12, 20)) is None
    assert cal.cover_period(date(2026, 2, 6)) == date(2026, 1, 2)
    assert cal.cover_period(date(2026, 1, 2)) == date(2026, 1, 2)
    assert cal.cover_period(date(2026, 6, 1)) is None  # more than 120 days later
    assert cal.cover_period(date(2024, 12, 1)) is None  # before any period end
    assert cal.label(date(2026, 1, 2)) == 2025


def test_describe_fiscal_year_end():
    assert describe_fiscal_year_end([date(2024, 12, 31), date(2025, 12, 31)]) == "12/31"
    assert describe_fiscal_year_end([date(2024, 12, 31), date(2026, 1, 2)]) == "01/02"  # 2 days
    assert (
        describe_fiscal_year_end([date(2022, 12, 30), date(2023, 12, 29), date(2026, 1, 2)])
        == "52/53-week year ending 2026-01-02"
    )
    assert describe_fiscal_year_end([date(2024, 2, 29), date(2025, 2, 28)]) == "02/28"


def test_month_rule_is_only_a_fallback():
    # the rule that used to decide everything: right for a June filer, wrong for a December
    # 52/53-week year end declared as January (which is why it no longer decides)
    assert fiscal_year_label(date(2025, 6, 30), 6) == 2025
    assert fiscal_year_label(date(2023, 12, 29), 1) == 2022


