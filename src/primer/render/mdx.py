"""Render primer.mdx: YAML frontmatter, numbered H2 sections, footnotes, Sources appendix.

Plain GitHub-flavored markdown with an .mdx extension: no imports, no JSX, no heading ids.
Citation style in the appendix follows the AlphaSense pattern:
  [^12]: 10-Q • Lockheed Martin Corp • 23 Jul 26 • "Quarterly Report Q2 2026" • https://…
Government records print their identifier:
  [^27]: USAspending • CONT_AWD_… • FY2026 • "Sentinel ICBM — EMD" • https://…
"""

from __future__ import annotations

from datetime import date
from typing import Any

import yaml

from primer import __version__
from primer.config import sources_config
from primer.evidence.store import EvidenceStore
from primer.render.citations import assign_footnotes
from primer.state import SECTION_TITLES, SourceRecord

DISCLAIMER = (
    "This primer was generated automatically from public sources as a research accelerator. "
    "It is not investment advice or a published opinion. Every factual claim carries a citation; "
    "read critically, follow the citations, and edit before relying on it."
)

TYPE_LABELS = {
    "api:edgar_xbrl": "XBRL (EDGAR)",
    "api:usaspending": "USAspending",
    "api:samgov": "SAM.gov",
    "press_release": "Press release",
    "earnings_call": "Earnings call",
    "news": "News",
    "trade_press": "Trade press",
    "rating_agency": "Rating agency",
    "web": "Web",
    "DEF14A": "DEF 14A",
    "earnings_release": "Earnings release",
    "gov_report": "Government report",
    "dod_announcement": "DoD contract announcement",
    "market_data": "Market data page",
    "presentation": "Investor presentation",
    "transcript": "Earnings call",
}


def _fmt_date(d: date | None) -> str:
    return d.strftime("%d %b %y") if d else "n.d."


def source_line(n: int, rec: SourceRecord) -> str:
    label = TYPE_LABELS.get(rec.type, rec.type)
    bits = [label]
    if rec.gov_id and rec.type.startswith("api:") and rec.type != "api:edgar_xbrl":
        bits = [rec.publisher, rec.gov_id]
    else:
        bits.append(rec.publisher)
    bits.append(_fmt_date(rec.published_date))
    bits.append(f'"{rec.title}"')
    bits.append(rec.url)  # bare URL: MDX reads <url> as JSX; GFM autolinks it
    if rec.access == "limited":
        bits.append("(access: limited)")
    return f"[^{n}]: " + " • ".join(bits)


def render(
    *,
    entity: dict[str, Any],
    as_of: str,
    run_id: str,
    sections_md: dict[int, str],
    coverage: dict[int, str],
    claims: list[dict[str, Any]],
    store: EvidenceStore,
    requested: list[int],
) -> tuple[str, dict[str, list[str]], list[str]]:
    """Return (mdx text, cited_by, ordered source ids)."""
    rewritten, order, cited_by = assign_footnotes(sections_md)

    fm = {
        "company": entity.get("name"),
        "ticker": entity.get("ticker"),
        "cik": entity.get("cik"),
        "exchange": entity.get("exchange"),
        "is_public": bool(entity.get("is_public")),
        "as_of": as_of,
        "run_id": run_id,
        "generator_version": __version__,
        "trace_id": run_id,
        "coverage": {str(s): coverage.get(s, "unavailable") for s in sorted(requested)},
        "source_limits": [
            *sources_config().get("source_limits", []),
            *(
                [
                    sources_config().get(
                        "private_source_limit",
                        "Private company: no SEC financial statements; financial figures are "
                        "press-reported and unaudited",
                    )
                ]
                if entity.get("private")
                else []
            ),
        ],
        "disclaimer": DISCLAIMER,
    }
    lines = [
        "---",
        yaml.safe_dump(fm, sort_keys=False, allow_unicode=True, width=1000).rstrip(),
        "---",
        "",
    ]
    lines.append(f"# {entity.get('name')} — Company Primer")
    lines.append("")
    lines.append(
        f"*As of {as_of}. Generated by ethan_sense {__version__}; see frontmatter for coverage and source limits.*"
    )
    lines.append("")

    for sec in sorted(requested):
        title = SECTION_TITLES[sec]
        lines.append(f"## {sec}. {title}")
        lines.append("")
        body = rewritten.get(sec)
        if body is None:
            body = f"> Coverage: unavailable — section {sec} was not produced in this run."
        lines.append(body.rstrip())
        lines.append("")

    lines.append("## Sources")
    lines.append("")
    for i, sid in enumerate(order, start=1):
        lines.append(source_line(i, store.get(sid)))
    lines.append("")

    derived = {}
    for c in claims:
        if c.get("concept") == "derived" and c.get("note"):
            derived.setdefault(c["metric"], c["note"])
    if derived:
        lines.append(
            "**Derived figures** (computed in-agent from the cited sources; no aggregator definition adopted):"
        )
        lines.append("")
        for metric, formula in sorted(derived.items()):
            lines.append(f"- {metric.replace('_', ' ')} = {formula.replace('_', ' ')}")
        lines.append("")

    return "\n".join(lines), cited_by, order
